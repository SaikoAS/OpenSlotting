'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {example}=require('./data/generate.cjs');
test('visible interpretation fixture is generated by the tested IO module, not fabricated scores',()=>{
  const expected=example(),actual=JSON.parse(fs.readFileSync(path.join(__dirname,'data/interpretation-example.json'),'utf8'));
  assert.deepEqual(actual,expected);
  const module=fs.readFileSync(path.join(__dirname,'data/interpretation-example.mjs'),'utf8').replace(/\r\n/g,'\n');
  assert.equal(module,'// Generated from the tested IO module and synthetic fixture.\nexport default '+JSON.stringify(expected,null,2)+';\n');
});
